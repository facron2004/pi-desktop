export function translate(text: string, language: AppLanguage): string {
  if (language !== 'zh-CN') {
    if (text === 'seconds-short') return 's'
    if (text === 'minutes-short') return 'm'
    if (text === 'Period Day') return 'Today'
    if (text === 'Period Week') return 'This week'
    if (text === 'Period Month') return 'This month'
    if (text === 'Period All') return 'All time'
    return text
  }
  const exported = /^Exported (.+)$/.exec(text)
  if (exported) return `已导出 ${exported[1]}`
  const committed = /^Committed (.+)$/.exec(text)
  if (committed) return `已提交 ${committed[1]}`
  const model = /^Model: (.+)$/.exec(text)
  if (model) return `模型：${model[1]}`
  const effort = /^Reasoning effort: (.+)$/.exec(text)
  if (effort) return `推理强度：${effort[1]}`
  const onlyModel = /^Only (.+) is available$/.exec(text)
  if (onlyModel) return `仅 ${onlyModel[1]} 可用`
  const earlierMessages = /^Up (\d+) messages$/.exec(text)
  if (earlierMessages) return `上 ${earlierMessages[1]} 条消息`
  const rateNotice = /^Retrying \(attempt (\d+)\/(\d+)\) — rate limit, next try in (\d+)s$/.exec(text)
  if (rateNotice) return `正在重试（第 ${rateNotice[1]}/${rateNotice[2]} 次），速率限制，${rateNotice[3]} 秒后再试`
  const activity = /^(\d+) (file reads?|search(?:es)?|edits?|commands? run|tool calls?)$/.exec(text)
  if (activity) {
    const units: Record<string, string> = {
      'file read': '次读取', 'file reads': '次读取', search: '次搜索', searches: '次搜索',
      edit: '次编辑', edits: '次编辑', 'command run': '次命令', 'commands run': '次命令',
      'tool call': '次工具调用', 'tool calls': '次工具调用'
    }
    return `${activity[1]} ${units[activity[2]]}`
  }
  const translation = zhCN[text]
  return translation ?? text
}

export function useT() {
  const language = useAppStore((state) => state.settings.language ?? 'en')
  return useCallback((text: string) => translate(text, language), [language])
}

/** What the composer and the welcome screen say while a project is coming up. */
export function openingLabel(
  workspace: { name?: string; path?: string } | undefined,
  t: (text: string) => string
): string {
  const name = workspace?.name?.trim() || (workspace?.path ? basename(workspace.path) : '')
  if (!name) return t('Starting the Pi runtime…')
  return t('Opening {project}…').replace('{project}', () => name)
}
